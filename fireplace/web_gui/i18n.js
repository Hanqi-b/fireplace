  function normalizeLocale(locale) {
    return locale === "enUS" ? "enUS" : "zhCN";
  }

  function interpolate(value, variables) {
    return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g, function (_, key) {
      return variables && variables[key] !== undefined ? String(variables[key]) : "{" + key + "}";
    });
  }

  function translate(key, variables, locale) {
    var selected = normalizeLocale(locale);
    var value = dictionaries[selected][key];
    if (value === undefined) {
      value = dictionaries.zhCN[key];
    }
    return interpolate(value === undefined ? key : value, variables);
  }

  window.FireplaceI18n = {
    locales: dictionaries,
    normalizeLocale: normalizeLocale,
    t: translate,
  };
